-- Find-or-create helpers. Each returns the id of the existing row when the same work exists.
create function lab.ensure_corpus_version(p_name text, p_content_hash text, p_manifest jsonb default '{}')
returns bigint language plpgsql as $$
declare v_id bigint;
begin
  insert into lab.corpus_version (name, config_hash, manifest)
  values (p_name, p_content_hash, coalesce(p_manifest, '{}'))
  on conflict (config_hash) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from lab.corpus_version where config_hash = p_content_hash;
  end if;
  return v_id;
end $$;

create function lab.ensure_chunk_set(p_corpus_version_id bigint, p_name text, p_config jsonb)
returns bigint language plpgsql as $$
declare v_id bigint;
begin
  insert into lab.chunk_set (corpus_version_id, name, config)
  values (p_corpus_version_id, p_name, p_config)
  on conflict (config_hash) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from lab.chunk_set
    where config_hash = lab.config_hash(p_corpus_version_id::text, p_config);
  end if;
  return v_id;
end $$;

create function lab.ensure_eval_set(p_name text, p_version text, p_content_hash text, p_description text default null)
returns bigint language plpgsql as $$
declare v_id bigint;
begin
  insert into lab.eval_set (name, version, config_hash, description)
  values (p_name, p_version, p_content_hash, p_description)
  on conflict (config_hash) do nothing
  returning id into v_id;
  if v_id is null then
    select id into v_id from lab.eval_set where config_hash = p_content_hash;
  end if;
  return v_id;
end $$;

-- One vector table per embedding space, because vector(dim) is fixed per column and
-- models have different dimensions. pgvector's HNSW index supports vector up to 2000 dims,
-- so larger models (e.g. 3072) are stored as halfvec (up to 4000 dims).
create function lab.create_embedding_space(
  p_chunk_set_id bigint, p_provider_id text, p_model text, p_dim int, p_location text,
  p_config jsonb default '{}'
) returns bigint
language plpgsql security definer set search_path = lab, public, pg_temp
as $$
declare
  v_id    bigint;
  v_table text;
  v_type  text := case when p_dim > 2000 then 'halfvec' else 'vector' end;
  v_ops   text := case when p_dim > 2000 then 'halfvec_cosine_ops' else 'vector_cosine_ops' end;
begin
  insert into lab.embedding_space (chunk_set_id, provider_id, model, dim, location, config)
  values (p_chunk_set_id, p_provider_id, p_model, p_dim, p_location, coalesce(p_config, '{}'))
  on conflict (config_hash) do nothing
  returning id into v_id;

  if v_id is null then  -- reuse: same chunks, same model
    select id into v_id from lab.embedding_space
    where config_hash = lab.config_hash(
      p_chunk_set_id::text || '/' || p_provider_id || '/' || p_model || '/' || p_dim::text, coalesce(p_config, '{}'));
    return v_id;
  end if;

  v_table := 'emb_' || v_id;
  execute format(
    'create table lab.%I (
       chunk_id   bigint primary key references lab.chunk (id),
       embedding  %s(%s) not null,
       created_at timestamptz not null default now()
     )', v_table, v_type, p_dim);
  execute format('create index on lab.%I using hnsw (embedding %s)', v_table, v_ops);
  execute format('grant select, insert on lab.%I to lab_backend', v_table);

  perform set_config('lab.allow_table_name', 'on', true);
  update lab.embedding_space set table_name = 'lab.' || v_table where id = v_id;
  perform set_config('lab.allow_table_name', '', true);
  return v_id;
end $$;

-- Load viz/providers.json (make providers). Providers are added or updated by id; enabled and
-- spend_cap_usd are only taken from the file for new providers, since the UI manages them afterwards.
-- Default models are replaced by the file's "defaults". Providers missing from the file are kept
-- (versions may still point at them) and reported back.
create function lab.load_providers(doc jsonb) returns text
language plpgsql as $$
declare
  p jsonb;
  added int := 0;
  updated int := 0;
  kept text;
begin
  perform set_config('lab.actor', 'me', true);
  perform set_config('lab.note', 'loaded from viz/providers.json', true);
  for p in select * from jsonb_array_elements(coalesce(doc -> 'providers', '[]')) loop
    if p ->> 'id' is null or p ->> 'location' not in ('local', 'cloud') then
      raise exception 'each provider needs an "id" and a "location" of local or cloud: %', p;
    end if;
    if exists (select 1 from lab.provider where id = p ->> 'id') then
      update lab.provider set
        name = coalesce(p ->> 'name', p ->> 'id'), kind = coalesce(p ->> 'kind', p ->> 'id'),
        location = p ->> 'location', endpoint = p ->> 'endpoint', key_env = p ->> 'key_env',
        models = coalesce(p -> 'models', '[]')
      where id = p ->> 'id'
        and (name, kind, location, endpoint, key_env, models) is distinct from
            (coalesce(p ->> 'name', p ->> 'id'), coalesce(p ->> 'kind', p ->> 'id'), p ->> 'location',
             p ->> 'endpoint', p ->> 'key_env', coalesce(p -> 'models', '[]'));
      if found then updated := updated + 1; end if;
    else
      insert into lab.provider (id, name, kind, location, endpoint, key_env, models, enabled, spend_cap_usd)
      values (p ->> 'id', coalesce(p ->> 'name', p ->> 'id'), coalesce(p ->> 'kind', p ->> 'id'), p ->> 'location',
              p ->> 'endpoint', p ->> 'key_env', coalesce(p -> 'models', '[]'),
              coalesce((p ->> 'enabled')::boolean, true), (p ->> 'spend_cap_usd')::numeric);
      added := added + 1;
    end if;
  end loop;

  delete from lab.default_model;
  insert into lab.default_model (kind, provider_id, model)
  select d.key, d.value ->> 'provider', d.value ->> 'model'
  from jsonb_each(coalesce(doc -> 'defaults', '{}')) d;

  select string_agg(id, ', ' order by id) into kept from lab.provider
  where id not in (select x ->> 'id' from jsonb_array_elements(coalesce(doc -> 'providers', '[]')) x);

  return format('%s added, %s updated, %s default models%s', added, updated,
                (select count(*) from lab.default_model),
                case when kept is null then '' else '; not in the file, kept: ' || kept end);
end $$;
revoke execute on function lab.load_providers(jsonb) from public;

