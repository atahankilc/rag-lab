-- Artifacts: the immutable, content-addressed building blocks that experiments point to.
--
--   corpus_version ─< document
--        └─< chunk_set ─< chunk
--               └─< embedding_space ── emb_<id> (vectors), projection (2D/3D points)
--   eval_set ─< eval_question ─< gold_evidence (document + char span)
--
-- Same chunking of the same corpus => same config_hash => the same chunk_set row is reused.
-- Same chunk_set + same embedding model => same embedding_space => the same vectors are reused.

