-- The default model per step kind (and 'embed' for the library), shown on the Providers page.
-- Also loaded from viz/providers.json.
create table lab.default_model (
  kind        text primary key,                       -- a step kind, e.g. 'embed', 'rerank', 'generate', 'judge'
  provider_id text not null references lab.provider (id),
  model       text not null
);

create table lab.corpus_version (
  id          bigint generated by default as identity primary key,
  name        text not null,
  manifest    jsonb not null default '{}',             -- how it was built: source, filters, counts
  config_hash text not null unique,                     -- content hash of the documents (sha256 of sorted doc hashes)
  created_at  timestamptz not null default now()
);

create table lab.document (
  id                bigint generated by default as identity primary key,
  corpus_version_id bigint not null references lab.corpus_version (id),
  external_id       text not null,                      -- the id in the source data, e.g. dsid_...
  source            text,                               -- confluence, slack, jira, ...
  title             text,
  author            text,
  project           text,
  doc_date          timestamptz,
  metadata          jsonb not null default '{}',
  text              text not null,
  content_hash      text,
  char_count        int generated always as (char_length(text)) stored,
  unique (corpus_version_id, external_id)
);

create table lab.chunk_set (
  id                bigint generated by default as identity primary key,
  corpus_version_id bigint not null references lab.corpus_version (id),
  name              text not null,                      -- human label, e.g. 'fixed-512'
  config            jsonb not null,                     -- {"strategy": "fixed", "size": 512, "overlap": 0, ...}
  config_hash       text generated always as (lab.config_hash(corpus_version_id::text, config)) stored unique,
  created_at        timestamptz not null default now()
);

create table lab.chunk (
  id              bigint generated by default as identity primary key,
  chunk_set_id    bigint not null references lab.chunk_set (id),
  document_id     bigint not null references lab.document (id),
  ord             int not null,                         -- position inside the document
  char_start      int not null,
  char_end        int not null,
  token_count     int,
  parent_chunk_id bigint references lab.chunk (id),     -- parent-child chunking
  text            text not null,
  check (char_end > char_start),
  unique (chunk_set_id, document_id, ord)
);
create index on lab.chunk (document_id);

create table lab.embedding_space (
  id           bigint generated by default as identity primary key,
  chunk_set_id bigint not null references lab.chunk_set (id),
  provider_id  text not null references lab.provider (id),
  model        text not null,
  dim          int not null check (dim > 0),
  location     text not null check (location in ('local', 'cloud')),
  config       jsonb not null default '{}',             -- e.g. {"normalize": true, "prefix": "passage: "}
  config_hash  text generated always as (
                 lab.config_hash(chunk_set_id::text || '/' || provider_id || '/' || model || '/' || dim::text, config)
               ) stored unique,
  table_name   text,                                    -- lab.emb_<id>, set by create_embedding_space
  -- filled once, after the vectors are written: {"vectors": 212, "build_ms": 5400, "index_bytes": 1830000, ...}
  build_stats  jsonb,
  created_at   timestamptz not null default now()
);

-- 2D/3D coordinates of every chunk in a space, for the Space view.
create table lab.projection (
  space_id bigint not null references lab.embedding_space (id),
  method   text not null,                               -- 'umap', 'pca'
  chunk_id bigint not null references lab.chunk (id),
  x        real not null,
  y        real not null,
  z        real,
  params   jsonb not null default '{}',
  primary key (space_id, method, chunk_id)
);

create table lab.eval_set (
  id          bigint generated by default as identity primary key,
  name        text not null,
  version     text not null,
  description text,
  config_hash text not null unique,                     -- content hash of the questions
  created_at  timestamptz not null default now(),
  unique (name, version)
);

create table lab.eval_question (
  id           bigint generated by default as identity primary key,
  eval_set_id  bigint not null references lab.eval_set (id),
  external_id  text not null,                           -- e.g. qst_0001
  qtype        text not null,                           -- basic, semantic, constrained, conflicting_info, ...
  tags         text[] not null default '{}',
  source_types text[] not null default '{}',
  question     text not null,
  gold_answer  text,
  answer_facts jsonb not null default '[]',
  unique (eval_set_id, external_id)
);

-- Gold evidence is a document + char span, not a chunk id, so it survives rechunking.
-- A chunk is relevant to a question if it overlaps any of the question's spans.
create table lab.gold_evidence (
  id          bigint generated by default as identity primary key,
  question_id bigint not null references lab.eval_question (id),
  document_id bigint not null references lab.document (id),
  char_start  int not null,
  char_end    int not null,
  check (char_end > char_start)
);
create index on lab.gold_evidence (question_id, document_id);

-- Where the query lands in a space (one point per question per space), for the Space view.
create table lab.query_projection (
  space_id    bigint not null references lab.embedding_space (id),
  method      text not null,
  question_id bigint not null references lab.eval_question (id),
  x           real not null,
  y           real not null,
  z           real,
  primary key (space_id, method, question_id)
);

