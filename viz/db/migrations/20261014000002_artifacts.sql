-- Providers are configuration, loaded from viz/providers.json (make providers). The UI can toggle
-- them and cap their spend. Never store API keys here: key_env names the .env variable that holds it.
create table lab.provider (
  id            text primary key,                     -- 'openai', 'ollama', 'st-local', 'anthropic', ...
  name          text not null,
  kind          text not null,                        -- free text: 'openai', 'ollama', 'sentence-transformers', ...
  location      text not null check (location in ('local', 'cloud')),
  endpoint      text,
  key_env       text,                                 -- e.g. 'OPENAI_API_KEY'; null for local providers
  -- [{"name": "gpt-5-mini", "kinds": ["generate"], "price_in_per_1m": 0.25, "price_out_per_1m": 2.0, "dim": null}]
  models        jsonb not null default '[]',
  enabled       boolean not null default true,
  spend_cap_usd numeric(12, 2),
  created_at    timestamptz not null default now()
);

-- Pipeline step kinds the UI knows: a label and a one-line description, like metric_def for metrics.
-- A version may use any kind; unknown kinds still render, labelled with the kind itself.
--   phase 'index' = building the library once (ingest, chunk, embed, index), a fixed shape
--   phase 'query' = per question, configurable steps in any order
create table lab.step_def (
  kind        text primary key,
  phase       text not null check (phase in ('index', 'query')),
  label       text not null,
  description text not null,
  sort        int not null default 100
);

