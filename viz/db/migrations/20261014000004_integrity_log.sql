-- Integrity: nothing is overwritten, and everything that happens is logged.
--
--   artifacts           no UPDATE / DELETE / TRUNCATE, ever
--   experiment          only status and is_baseline may change (config changes = new experiment)
--   run                 queued -> running -> done | failed; finished runs are frozen
--   results / events    insert only, and only while the run is open
--   log_event           append-only
--
-- There is no escape hatch: to start over, drop the database volume (make reset).

-- migrate:up

create table lab.log_event (
  id            bigint generated by default as identity primary key,
  ts            timestamptz not null default now(),
  actor         text not null check (actor in ('me', 'system', 'model')),
  action        text not null,                         -- 'experiment.create', 'run.done', 'provider.update', ...
  target_type   text,
  target_id     text,
  experiment_id bigint,                                -- no FK: the log must never block anything
  before        jsonb,
  after         jsonb,
  note          text
);
create index on lab.log_event (ts desc);

create function lab.reject_change() returns trigger
language plpgsql as $$
begin
  raise exception '% on lab.% is not allowed: % rows are immutable', tg_op, tg_table_name, tg_table_name
    using errcode = 'restrict_violation',
          hint = 'Create a new row (or a new experiment with parent_id) instead of changing an existing one.';
end $$;

create function lab.reject_truncate() returns trigger
language plpgsql as $$
begin
  raise exception 'TRUNCATE on lab.% is not allowed', tg_table_name using errcode = 'restrict_violation';
end $$;

do $$
declare t text;
begin
  foreach t in array array[
    'corpus_version', 'document', 'chunk_set', 'chunk', 'projection', 'query_projection',
    'eval_set', 'eval_question', 'gold_evidence', 'experiment_note',
    'question_result', 'retrieval_hit', 'run_metric', 'run_event', 'log_event'
  ] loop
    execute format('create trigger immutable before update or delete on lab.%I
                    for each row execute function lab.reject_change()', t);
  end loop;
  foreach t in array array[
    'corpus_version', 'document', 'chunk_set', 'chunk', 'projection', 'query_projection', 'embedding_space',
    'eval_set', 'eval_question', 'gold_evidence', 'experiment', 'experiment_note', 'run',
    'question_result', 'retrieval_hit', 'run_metric', 'run_event', 'log_event'
  ] loop
    execute format('create trigger no_truncate before truncate on lab.%I
                    for each statement execute function lab.reject_truncate()', t);
  end loop;
end $$;

-- embedding_space: immutable, except table_name (set once by create_embedding_space)
-- and build_stats (filled once by the backend after writing the vectors).
create function lab.guard_embedding_space() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'DELETE on lab.embedding_space is not allowed' using errcode = 'restrict_violation';
  end if;
  if (to_jsonb(new) - 'table_name' - 'build_stats' - 'config_hash') <> (to_jsonb(old) - 'table_name' - 'build_stats' - 'config_hash')
     or (new.table_name is distinct from old.table_name and coalesce(current_setting('lab.allow_table_name', true), '') <> 'on')
     or (new.build_stats is distinct from old.build_stats and old.build_stats is not null) then
    raise exception 'embedding_space % is immutable (build_stats can be set once)', old.id
      using errcode = 'restrict_violation';
  end if;
  return new;
end $$;
create trigger guard before update or delete on lab.embedding_space
  for each row execute function lab.guard_embedding_space();

-- config.steps must be a list of objects, each with a unique non-empty "id" and a "kind".
create function lab.check_steps(p_slug text, p_config jsonb) returns void
language plpgsql as $$
declare
  s jsonb;
  ids text[] := '{}';
begin
  if not (p_config ? 'steps') then return; end if;
  if jsonb_typeof(p_config -> 'steps') <> 'array' then
    raise exception 'experiment %: config.steps must be a list', p_slug using errcode = 'check_violation';
  end if;
  for s in select * from jsonb_array_elements(p_config -> 'steps') loop
    if jsonb_typeof(s) <> 'object' or coalesce(s ->> 'id', '') = '' or coalesce(s ->> 'kind', '') = '' then
      raise exception 'experiment %: every step needs an "id" and a "kind": %', p_slug, s using errcode = 'check_violation';
    end if;
    if (s ->> 'id') = any (ids) then
      raise exception 'experiment %: step id "%" is used twice', p_slug, s ->> 'id' using errcode = 'check_violation';
    end if;
    if (s ->> 'id') in ('total', 'ingest', 'chunk', 'embed', 'index') then
      raise exception 'experiment %: "%" is reserved and cannot be a step id', p_slug, s ->> 'id' using errcode = 'check_violation';
    end if;
    ids := ids || (s ->> 'id');
  end loop;
end $$;

-- experiment: config is frozen. Only status and is_baseline can change.
-- (config_hash is left out of the comparisons: generated columns are only computed after BEFORE triggers.)
create function lab.guard_experiment() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'DELETE on lab.experiment is not allowed' using errcode = 'restrict_violation';
  end if;
  if tg_op = 'INSERT' then
    -- the artifacts must belong together
    if not exists (select 1 from lab.chunk_set cs
                   join lab.embedding_space es on es.chunk_set_id = cs.id
                   where cs.id = new.chunk_set_id and es.id = new.embedding_space_id
                     and cs.corpus_version_id = new.corpus_version_id) then
      raise exception 'experiment %: chunk_set must belong to the corpus_version and embedding_space to the chunk_set', new.slug
        using errcode = 'foreign_key_violation';
    end if;
    perform lab.check_steps(new.slug, new.config);
    return new;
  end if;
  if (to_jsonb(new) - 'status' - 'is_baseline' - 'config_hash') <> (to_jsonb(old) - 'status' - 'is_baseline' - 'config_hash') then
    raise exception 'experiment % is immutable: only status and is_baseline can change', old.slug
      using errcode = 'restrict_violation',
            hint = 'To change the config, create a new experiment with parent_id = ' || old.id || '.';
  end if;
  return new;
end $$;
create trigger guard before insert or update or delete on lab.experiment
  for each row execute function lab.guard_experiment();

-- run: a small state machine. Finished runs are frozen.
create function lab.guard_run() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'DELETE on lab.run is not allowed' using errcode = 'restrict_violation';
  end if;
  if tg_op = 'INSERT' then
    if new.status not in ('queued', 'running') then
      raise exception 'a run starts as queued or running, not %', new.status using errcode = 'check_violation';
    end if;
    if new.status = 'running' then new.started_at := coalesce(new.started_at, now()); end if;
    return new;
  end if;
  if old.status in ('done', 'failed') then
    raise exception 'run % is % and can no longer change', old.id, old.status using errcode = 'restrict_violation';
  end if;
  if new.experiment_id <> old.experiment_id or new.overrides <> old.overrides or new.queued_at <> old.queued_at then
    raise exception 'run %: experiment_id, overrides and queued_at are fixed', old.id using errcode = 'restrict_violation';
  end if;
  if not (old.status = new.status
          or (old.status = 'queued'  and new.status in ('running', 'failed'))
          or (old.status = 'running' and new.status in ('done', 'failed'))) then
    raise exception 'run %: cannot go from % to %', old.id, old.status, new.status using errcode = 'check_violation';
  end if;
  if new.status = 'running' then new.started_at := coalesce(new.started_at, now()); end if;
  if new.status in ('done', 'failed') then new.finished_at := coalesce(new.finished_at, now()); end if;
  return new;
end $$;
create trigger guard before insert or update or delete on lab.run
  for each row execute function lab.guard_run();

-- Results and events can only be added to an open run.
create function lab.require_open_run() returns trigger
language plpgsql as $$
declare v_status text;
begin
  select status into v_status from lab.run where id = new.run_id;
  if v_status is null then
    raise exception 'run % does not exist', new.run_id using errcode = 'foreign_key_violation';
  end if;
  if v_status = 'running' or (tg_table_name = 'run_event' and v_status = 'queued') then
    return new;
  end if;
  raise exception 'run % is %: results can only be written while it is running', new.run_id, v_status
    using errcode = 'restrict_violation';
end $$;
do $$
declare t text;
begin
  foreach t in array array['question_result', 'retrieval_hit', 'run_metric', 'run_event'] loop
    execute format('create trigger open_run before insert on lab.%I
                    for each row execute function lab.require_open_run()', t);
  end loop;
end $$;

-- Logging ---------------------------------------------------------------------------------
-- Actor and note come from transaction settings, so callers can say who did it:
--   select set_config('lab.actor', 'me', true);   -- me | system | model (default: system)
--   select set_config('lab.note', 'why', true);

create function lab.write_log(
  p_action text, p_target_type text, p_target_id text, p_experiment_id bigint,
  p_before jsonb default null, p_after jsonb default null,
  p_ts timestamptz default null, p_note text default null, p_actor text default null
) returns void
language sql security definer set search_path = lab, pg_temp
as $$
  insert into lab.log_event (ts, actor, action, target_type, target_id, experiment_id, before, after, note)
  values (
    coalesce(p_ts, now()),
    coalesce(p_actor, nullif(current_setting('lab.actor', true), ''), 'system'),
    p_action, p_target_type, p_target_id, p_experiment_id, p_before, p_after,
    coalesce(p_note, nullif(current_setting('lab.note', true), '')))
$$;

-- Only the changed keys of a row, as {"before": {...}, "after": {...}}.
create function lab.changed_fields(p_old jsonb, p_new jsonb) returns table (before jsonb, after jsonb)
language sql immutable as $$
  select coalesce(jsonb_object_agg(k, p_old -> k), '{}'), coalesce(jsonb_object_agg(k, p_new -> k), '{}')
  from jsonb_object_keys(p_new) k
  where (p_old -> k) is distinct from (p_new -> k)
$$;

create function lab.log_insert() returns trigger
language plpgsql as $$
declare
  v_row jsonb := to_jsonb(new);
begin
  case tg_table_name
    when 'corpus_version' then
      perform lab.write_log('corpus.register', 'corpus_version', new.id::text, null,
        null, jsonb_build_object('name', new.name, 'hash', left(new.config_hash, 12)), new.created_at);
    when 'chunk_set' then
      perform lab.write_log('chunk_set.create', 'chunk_set', new.id::text, null,
        null, jsonb_build_object('name', new.name, 'config', new.config), new.created_at);
    when 'embedding_space' then
      perform lab.write_log('space.create', 'embedding_space', new.id::text, null,
        null, jsonb_build_object('provider', new.provider_id, 'model', new.model, 'dim', new.dim, 'location', new.location));
    when 'eval_set' then
      perform lab.write_log('eval_set.create', 'eval_set', new.id::text, null,
        null, jsonb_build_object('name', new.name, 'version', new.version), new.created_at);
    when 'experiment' then
      perform lab.write_log('experiment.create', 'experiment', new.id::text, new.id,
        null, jsonb_build_object('slug', new.slug, 'name', new.name, 'parent_id', new.parent_id),
        new.created_at, new.note, coalesce(nullif(current_setting('lab.actor', true), ''), 'me'));
    when 'experiment_note' then
      perform lab.write_log('experiment.note', 'experiment', new.experiment_id::text, new.experiment_id,
        null, jsonb_build_object('body', new.body), new.created_at, new.body, new.actor);
    when 'run' then
      perform lab.write_log('run.' || case new.status when 'queued' then 'queue' else 'start' end,
        'run', new.id::text, new.experiment_id,
        null, jsonb_build_object('status', new.status, 'overrides', new.overrides),
        coalesce(new.started_at, new.queued_at));
    when 'provider' then
      perform lab.write_log('provider.add', 'provider', new.id, null,
        null, v_row - 'models' - 'created_at', new.created_at);
  end case;
  return new;
end $$;

create function lab.log_update() returns trigger
language plpgsql as $$
declare
  c record;
begin
  select * into c from lab.changed_fields(to_jsonb(old), to_jsonb(new));
  if c.after = '{}'::jsonb then return new; end if;
  case tg_table_name
    when 'experiment' then
      if new.is_baseline is distinct from old.is_baseline then
        perform lab.write_log(case when new.is_baseline then 'baseline.pin' else 'baseline.unpin' end,
          'experiment', new.id::text, new.id, c.before, c.after);
      else
        perform lab.write_log('experiment.update', 'experiment', new.id::text, new.id, c.before, c.after);
      end if;
    when 'run' then
      if new.status is distinct from old.status then
        perform lab.write_log('run.' || case new.status when 'running' then 'start' when 'done' then 'done' else 'fail' end,
          'run', new.id::text, new.experiment_id,
          jsonb_build_object('status', old.status),
          jsonb_build_object('status', new.status, 'total_cost_usd', new.total_cost_usd, 'error', new.error),
          case new.status when 'running' then new.started_at else new.finished_at end,
          null, 'system');
      end if;
    when 'embedding_space' then
      if new.build_stats is distinct from old.build_stats then
        perform lab.write_log('space.build', 'embedding_space', new.id::text, null, null, new.build_stats);
      end if;
    when 'provider' then
      perform lab.write_log('provider.update', 'provider', new.id, null, c.before, c.after);
    when 'default_model' then
      perform lab.write_log('default_model.update', 'default_model', new.kind, null, c.before, c.after);
  end case;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['corpus_version', 'chunk_set', 'embedding_space', 'eval_set', 'experiment',
                           'experiment_note', 'run', 'provider'] loop
    execute format('create trigger log_insert after insert on lab.%I
                    for each row execute function lab.log_insert()', t);
  end loop;
  foreach t in array array['experiment', 'run', 'embedding_space', 'provider', 'default_model'] loop
    execute format('create trigger log_update after update on lab.%I
                    for each row execute function lab.log_update()', t);
  end loop;
end $$;


