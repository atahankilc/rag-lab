-- Experiments (versions of the system) and their runs (evaluations).
--
--   experiment ── points to: corpus_version, chunk_set, embedding_space, eval_set (the library)
--       │         + pipeline config (jsonb): an ordered list of per-question steps
--       ├─< experiment_note
--       └─< run ─< run_event
--                ├─< question_result   (per question)
--                ├─< retrieval_hit     (per question x chunk x stage)
--                └─< run_metric        (aggregates)

-- migrate:up

create table lab.experiment (
  id                 bigint generated by default as identity primary key,
  slug               text not null unique,               -- 'v0', 'v1', ...
  name               text not null,
  parent_id          bigint references lab.experiment (id),
  note               text,                               -- why I tried this
  corpus_version_id  bigint not null references lab.corpus_version (id),
  chunk_set_id       bigint not null references lab.chunk_set (id),
  embedding_space_id bigint not null references lab.embedding_space (id),
  eval_set_id        bigint not null references lab.eval_set (id),
  -- {"steps": [{"id": "dense", "kind": "retrieve", ...}, {"id": "rerank", "kind": "rerank", ...}, ...], "advanced": {...}}
  -- The list order is the pipeline order. Each step has a unique "id" and a "kind" (see lab.step_def).
  config             jsonb not null default '{}',
  config_hash        text generated always as (lab.config_hash(
                       corpus_version_id::text || '/' || chunk_set_id::text || '/' ||
                       embedding_space_id::text || '/' || eval_set_id::text, config)) stored unique,
  status             text not null default 'active' check (status in ('active', 'archived')),
  is_baseline        boolean not null default false,
  created_at         timestamptz not null default now()
);
create unique index experiment_one_baseline on lab.experiment (is_baseline) where is_baseline;

-- Notes are added later, never edited.
create table lab.experiment_note (
  id            bigint generated by default as identity primary key,
  experiment_id bigint not null references lab.experiment (id),
  body          text not null,
  actor         text not null default 'me',
  created_at    timestamptz not null default now()
);

create table lab.run (
  id             bigint generated by default as identity primary key,
  experiment_id  bigint not null references lab.experiment (id),
  status         text not null default 'queued' check (status in ('queued', 'running', 'done', 'failed')),
  overrides      jsonb not null default '{}',            -- one-off config changes for this run
  queued_at      timestamptz not null default now(),
  started_at     timestamptz,
  finished_at    timestamptz,
  total_cost_usd numeric(12, 6),
  stage_cost     jsonb not null default '{}',            -- by step id: {"generate": 0.031, "judge": 0.12, ...}
  git_commit     text,
  environment    jsonb not null default '{}',            -- {"python": "3.12", "host": "...", ...}
  worker         text,                                   -- who claimed it
  error          text
);
create index on lab.run (experiment_id, status);

create table lab.question_result (
  run_id          bigint not null references lab.run (id),
  question_id     bigint not null references lab.eval_question (id),
  answer          text,
  citations       jsonb not null default '[]',           -- [{"chunk_id": 12, "marker": "[1]"}]
  metrics         jsonb not null default '{}',           -- {"correctness": 1, "recall_at_k": 0.5, ...}
  latency_ms      jsonb not null default '{}',           -- by step id, + "total": {"dense": 130, "generate": 980, "total": 1109}
  tokens          jsonb not null default '{}',           -- {"prompt": 1800, "completion": 120, "judge": 2400}
  cost            jsonb not null default '{}',           -- by step id: {"generate": 0.0007, "judge": 0.004}
  cost_usd        numeric(12, 6),                        -- total without judge
  judge_rationale text,
  created_at      timestamptz not null default now(),
  primary key (run_id, question_id)
);

create table lab.retrieval_hit (
  run_id      bigint not null references lab.run (id),
  question_id bigint not null references lab.eval_question (id),
  stage       text not null,                         -- the id of the step that produced this list
  rank        int not null check (rank >= 1),
  chunk_id    bigint not null references lab.chunk (id),
  score       double precision,
  primary key (run_id, question_id, stage, rank)
);
create index on lab.retrieval_hit (chunk_id);

create table lab.run_metric (
  run_id bigint not null references lab.run (id),
  name   text not null,                                  -- matches metric_def.name when known
  scope  text not null default 'all',                    -- 'all', 'tag:<qtype>', 'step:<step id>'
  value  double precision not null,
  primary key (run_id, name, scope)
);

create table lab.run_event (
  id      bigint generated by default as identity primary key,
  run_id  bigint not null references lab.run (id),
  ts      timestamptz not null default now(),
  stage   text,                                          -- ingest, chunk, embed, index, or a step id
  level   text not null default 'info' check (level in ('debug', 'info', 'warn', 'error')),
  message text not null,
  data    jsonb not null default '{}'                    -- {"state": "start"|"progress"|"done", "done": 17, "total": 30}
);
create index on lab.run_event (run_id, ts);

